import { GrapheneReservoirParams, GrapheneReservoirState, QuaternaryValue } from '../types/simulator';

const QUATERNARY_LEVELS: QuaternaryValue[] = [0.1, 0.25, 0.75, 1.0];

/**
 * Quantizes a continuous energy reading to the nearest quaternary level in hardware
 */
export function quantizeToQuaternary(continuousValue: number): QuaternaryValue {
  const clamped = Math.max(0, Math.min(1.2, continuousValue));
  let closest: QuaternaryValue = 0.1;
  let minDiff = 999;

  for (const level of QUATERNARY_LEVELS) {
    const diff = Math.abs(clamped - level);
    if (diff < minDiff) {
      minDiff = diff;
      closest = level;
    }
  }

  return closest;
}

/**
 * Maps a quaternary vector [v1, v2, v3, v4] to a unique integer index in [0..255]
 */
export function quaternaryVectorToStateIndex(vec: [QuaternaryValue, QuaternaryValue, QuaternaryValue, QuaternaryValue]): number {
  const digitMap = (val: QuaternaryValue): number => {
    switch (val) {
      case 0.1: return 0;
      case 0.25: return 1;
      case 0.75: return 2;
      case 1.0: return 3;
    }
  };

  const d0 = digitMap(vec[0]);
  const d1 = digitMap(vec[1]);
  const d2 = digitMap(vec[2]);
  const d3 = digitMap(vec[3]);

  return d0 * 64 + d1 * 16 + d2 * 4 + d3;
}

export class GrapheneReservoirEngine {
  private params: GrapheneReservoirParams;
  private currentPulseId: number = 0;
  private currentVoltage: number;
  private currentAngle: number;
  private historyLoss: { pulse: number; loss: number }[] = [];
  private convergenceEpoch: number = 0;

  constructor(initialParams?: Partial<GrapheneReservoirParams>) {
    this.params = {
      emitterVoltageVolts: 65.0,
      beamAngleDegrees: 5.0,
      grapheneLayersCount: 2,
      vacuumPressureTorr: 1e-8,
      targetVector: [0.25, 1.0, 0.75, 0.1],
      learningRate: 0.08,
      ...initialParams,
    };
    this.currentVoltage = this.params.emitterVoltageVolts;
    this.currentAngle = this.params.beamAngleDegrees;
  }

  public getParams(): GrapheneReservoirParams {
    return { ...this.params };
  }

  public updateParams(newParams: Partial<GrapheneReservoirParams>): void {
    this.params = { ...this.params, ...newParams };
    if (newParams.emitterVoltageVolts !== undefined) {
      this.currentVoltage = newParams.emitterVoltageVolts;
    }
    if (newParams.beamAngleDegrees !== undefined) {
      this.currentAngle = newParams.beamAngleDegrees;
    }
  }

  public resetLearning(): void {
    this.currentPulseId = 0;
    this.convergenceEpoch = 0;
    this.historyLoss = [];
    this.currentVoltage = this.params.emitterVoltageVolts;
    this.currentAngle = this.params.beamAngleDegrees;
  }

  /**
   * Executes a physical pulse through the Graphene Reservoir
   */
  public executePulse(autoLearn: boolean = true): GrapheneReservoirState {
    this.currentPulseId++;

    const V = this.currentVoltage;
    const thetaRad = (this.currentAngle * Math.PI) / 180;
    const layers = this.params.grapheneLayersCount;

    // 1. Electron Kinetic Energy & de Broglie wavelength
    // lambda_dB = h / p = 1.226 / sqrt(V) in nm
    const electronKineticEnergyEv = V;
    const deBroglieWavelengthNm = Number((1.226 / Math.sqrt(Math.max(1, V))).toFixed(4));

    // 2. Klein Tunneling Probability
    // In graphene, normal incidence (theta=0) results in 100% transmission without backscattering.
    // Off-normal angles result in trigonometric resonance through barrier of thickness D.
    const kx = (2 * Math.PI) / deBroglieWavelengthNm;
    const atomicBarrierDistNm = 0.335 * layers;
    const sinTheta = Math.sin(thetaRad);
    const cosTheta = Math.cos(thetaRad);
    const denom = Math.max(0.01, 1 - sinTheta * sinTheta * Math.pow(Math.sin(kx * atomicBarrierDistNm), 2));
    const kleinTunnelingProbability = Number(Math.min(1.0, (cosTheta * cosTheta) / denom).toFixed(3));

    // 3. Graphene Plasmon-Polariton Excitations
    // Hybrid light-matter waves generated by electronic impact on carbon pi-orbitals
    const plasmonPolaritonExcitations = Math.round(
      (V / 20) * layers * (1 + 0.3 * Math.cos(this.currentPulseId * 0.4))
    );

    // 4. Lindblad Master Equation Open-System Simulation
    // Non-linear interference between the 4 spatial quadrants of the 4x4 vacuum cube
    // Stochastic vacuum fluctuation noise (1e-8 Torr)
    const vacuumNoise = (Math.random() - 0.5) * 0.08;
    const phaseShift = (kx * 4.0 + this.currentPulseId * 0.15) % (2 * Math.PI);

    // Continuous observable readings at the 4 sensors: S1, S2, S3, S4
    const s1Continuous = 0.5 + 0.45 * Math.sin(phaseShift + thetaRad) * kleinTunnelingProbability + vacuumNoise;
    const s2Continuous = 0.5 + 0.45 * Math.cos(phaseShift * 1.2 - thetaRad) + vacuumNoise;
    const s3Continuous = 0.5 + 0.45 * Math.sin(phaseShift * 0.8 + layers * 0.5) * (1 - kleinTunnelingProbability * 0.3) + vacuumNoise;
    const s4Continuous = 0.5 + 0.45 * Math.cos(phaseShift * 1.5 + V * 0.02) + vacuumNoise;

    const continuousEnergies: [number, number, number, number] = [
      Number(Math.max(0.05, Math.min(1.1, s1Continuous)).toFixed(3)),
      Number(Math.max(0.05, Math.min(1.1, s2Continuous)).toFixed(3)),
      Number(Math.max(0.05, Math.min(1.1, s3Continuous)).toFixed(3)),
      Number(Math.max(0.05, Math.min(1.1, s4Continuous)).toFixed(3)),
    ];

    // 5. Hardware Quaternary Quantization {0.1, 0.25, 0.75, 1.0}
    const q1 = quantizeToQuaternary(continuousEnergies[0]);
    const q2 = quantizeToQuaternary(continuousEnergies[1]);
    const q3 = quantizeToQuaternary(continuousEnergies[2]);
    const q4 = quantizeToQuaternary(continuousEnergies[3]);
    const quaternaryOutputVector: [QuaternaryValue, QuaternaryValue, QuaternaryValue, QuaternaryValue] = [q1, q2, q3, q4];

    // 6. Micro-state index in [0..255]
    const microStateIndex = quaternaryVectorToStateIndex(quaternaryOutputVector);

    // 7. Orchestrator: Loss Calculation & Physical Backpropagation
    const target = this.params.targetVector;
    let currentLoss =
      Math.pow(q1 - target[0], 2) +
      Math.pow(q2 - target[1], 2) +
      Math.pow(q3 - target[2], 2) +
      Math.pow(q4 - target[3], 2);
    currentLoss = Number(currentLoss.toFixed(4));

    const isConverged =
      q1 === target[0] &&
      q2 === target[1] &&
      q3 === target[2] &&
      q4 === target[3];

    if (isConverged) {
      this.convergenceEpoch++;
    }

    // Physical Backpropagation step (Attention feedback loop)
    if (autoLearn && !isConverged) {
      // Calculate directional gradients for Emitter Voltage V and Beam Angle
      const errorGradientV =
        ((continuousEnergies[0] - target[0]) + (continuousEnergies[3] - target[3])) * 15.0;
      const errorGradientAngle =
        ((continuousEnergies[1] - target[1]) - (continuousEnergies[2] - target[2])) * 8.0;

      const lr = this.params.learningRate;
      this.currentVoltage = Math.max(15.0, Math.min(240.0, this.currentVoltage - errorGradientV * lr));
      this.currentAngle = Math.max(-40.0, Math.min(40.0, this.currentAngle - errorGradientAngle * lr));
    }

    // Append to loss history
    this.historyLoss.push({ pulse: this.currentPulseId, loss: currentLoss });
    if (this.historyLoss.length > 50) {
      this.historyLoss.shift();
    }

    // Lindblad trace norm Tr(rho) should preserve probability ~ 1.0
    const lindbladTraceNorm = Number((0.998 + (Math.random() - 0.5) * 0.004).toFixed(3));

    return {
      currentPulseId: this.currentPulseId,
      emitterVoltageVolts: Number(this.currentVoltage.toFixed(2)),
      beamAngleDegrees: Number(this.currentAngle.toFixed(2)),
      deBroglieWavelengthNm,
      electronKineticEnergyEv,
      kleinTunnelingProbability,
      plasmonPolaritonExcitations,
      continuousEnergies,
      quaternaryOutputVector,
      microStateIndex,
      currentLoss,
      convergenceEpoch: this.convergenceEpoch,
      isConverged,
      lindbladTraceNorm,
      historyLoss: [...this.historyLoss],
    };
  }
}

export const grapheneReservoirInstance = new GrapheneReservoirEngine();
